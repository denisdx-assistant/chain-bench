def main():
    # проверки
    assert ivan + pushok == 120, ivan + pushok
    assert sum([5, 3, 5, 9]) + 17 == 39
    assert 110 == 110
    for t in TASKS:
        assert isinstance(t["answer"], int), t["id"]
    ids = [t["id"] for t in TASKS]
    assert len(ids) == len(set(ids))

    json.dump(TASKS, open("tasks_final.json", "w"), ensure_ascii=False, indent=1)

    with open("tasks_final.md", "w") as f:
        f.write("# Итоговый набор задач — %d штук\n\n" % len(TASKS))
        f.write("> Ответы пересчитаны кодом ([[build_tasks.py]]), расхождений нет.\n")
        f.write("> Машиночитаемый формат: [[tasks_final.json]] · генератор датасетов: [[gen_noise.py]]\n")
        f.write("> Пример запроса с шумом: [[example_request.md]] · описание папки: [[README.md]]\n\n")
        for t in TASKS:
            f.write("## %d. %s\n\n" % (t["id"], t["title"]))
            f.write("*Происхождение: %s · тип: %s*\n\n" % (t["origin"], t["kind"]))
            for i, s in enumerate(t["statements"], 1):
                f.write("%d. %s\n" % (i, s))
            f.write("\n**Вопрос:** %s\n\n**Ответ:** `%d`\n" % (t["question"], t["answer"]))
            if t.get("check"):
                f.write("\n**Проверка:** %s\n" % t["check"])
            if t.get("note"):
                f.write("\n**Примечание:** %s\n" % t["note"])
            f.write("\n---\n\n")

    print("задач:", len(TASKS))
    for t in TASKS:
        print("  %2d | %-22s | ответ %5d | %s" % (t["id"], t["kind"], t["answer"], t["origin"]))


if __name__ == "__main__":
    main()
